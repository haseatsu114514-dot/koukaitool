// Regenerates src/lib/diagnosis/setsuiri.ts: the JST moment of each month's 節 (小寒 … 大雪), 1900–2100.
// lunar-typescript reports solar terms in UTC+8; they are shifted to UTC+9 and rounded to the nearest minute,
// the same convention as the National Astronomical Observatory of Japan's 暦要項.
import { writeFileSync } from "node:fs";
import { Solar } from "lunar-typescript";

const FIRST_YEAR = 1900, LAST_YEAR = 2100;
const TERMS = ["小寒", "立春", "惊蛰", "清明", "立夏", "芒种", "小暑", "立秋", "白露", "寒露", "立冬", "大雪"];
const pad = n => String(n).padStart(2, "0");
const lines = [];
for (let year = FIRST_YEAR; year <= LAST_YEAR; year++) {
  const table = Solar.fromYmd(year, 6, 1).getLunar().getJieQiTable();
  lines.push(TERMS.map((name, i) => {
    const t = table[name];
    const utc8 = Date.UTC(t.getYear(), t.getMonth() - 1, t.getDay(), t.getHour(), t.getMinute(), t.getSecond());
    const jst = new Date(Math.round(utc8 / 60_000) * 60_000 + 60 * 60 * 1000);
    if (jst.getUTCFullYear() !== year || jst.getUTCMonth() !== i) throw new Error(`${name} ${year} falls outside its month`);
    return `${pad(jst.getUTCDate())}${pad(jst.getUTCHours())}${pad(jst.getUTCMinutes())}`;
  }).join(" "));
}
const source = `// Generated by scripts/generate-setsuiri.mjs. Do not edit by hand.
export const SETSUIRI_FIRST_YEAR = ${FIRST_YEAR};
/** JST 節入り per year as twelve "DDHHMM" entries, 1月小寒 … 12月大雪. */
export const SETSUIRI_JST = [
${lines.map((line, i) => `  "${line}", // ${FIRST_YEAR + i}`).join("\n")}
];
`;
writeFileSync(new URL("../src/lib/diagnosis/setsuiri.ts", import.meta.url), source);
